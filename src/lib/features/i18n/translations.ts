/** Acepta códigos UI (es), Tesseract (spa), BCP-47 (es-ES) y 'auto'. */
export function resolveLocale(
  raw: string | undefined | null,
  fallback: LocaleCode = DEFAULT_LOCALE,
): LocaleCode {
  if (!raw) return fallback;
  const lower = raw.trim().toLowerCase();
  if (!lower || lower === "auto" || lower === "system") return fallback;
  const base = lower.split(/[-_]/)[0];
  const map: Record<string, LocaleCode> = {
    es: "es",
    spa: "es",
    en: "en",
    eng: "en",
    fr: "fr",
    fra: "fr",
    de: "de",
    deu: "de",
    ger: "de",
    pt: "pt",
    por: "pt",
    it: "it",
    ita: "it",
    zh: "zh",
    chi_sim: "zh",
    chi_tra: "zh",
    chn: "zh",
    cn: "zh",
    ja: "ja",
    jpn: "ja",
    jp: "ja",
    ko: "ko",
    kor: "ko",
    kr: "ko",
    ru: "ru",
    rus: "ru",
  };
  return map[lower] ?? map[base] ?? fallback;
}

export function isLocale(code: unknown): code is LocaleCode {
  return (
    typeof code === "string" &&
    (SUPPORTED_LOCALES as readonly string[]).includes(code)
  );
}

export function htmlLangOf(code: LocaleCode): string {
  return LANGUAGES.find((l) => l.code === code)?.html ?? code;
}

export function ocrCodeOf(code: LocaleCode): string {
  return LANGUAGES.find((l) => l.code === code)?.ocr ?? "eng";
}
